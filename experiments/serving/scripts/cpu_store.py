"""Materialize a same-node shared CPU catalogue inside a CPU-only allocation.

No GPU is used. Writes one sealed memfd, then retains it until --release exists.
Only the seven GPT-OSS projection families generated by prepare_assets are
accepted; normalization is checked against the pinned engine implementation.
"""
import argparse
import ast
import ctypes
import fcntl
import hashlib
import json
import os
from pathlib import Path
import socket
import time
from types import SimpleNamespace


def normalize(raw):
    import torch
    result = dict(raw)
    for name in list(raw):
        if '.q_proj.' in name:
            keys = [name.replace('.q_proj.', f'.{p}_proj.') for p in ('q','k','v')]
            result[name.replace('.q_proj.', '.qkv_proj.')] = torch.cat([result.pop(k) for k in keys], 0)
        elif '.gate_proj.' in name:
            up = name.replace('.gate_proj.', '.up_proj.')
            result[name.replace('.gate_proj.', '.gate_up_proj.')] = torch.cat([result.pop(name), result.pop(up)], 0)
    return result


def check_reference(raw, actual):
    """Execute the engine's real normalization methods without GPU imports."""
    import torch
    source = Path('engine/python/sglang/srt/lora/lora.py').read_text()
    klass = next(n for n in ast.parse(source).body if isinstance(n, ast.ClassDef) and n.name == 'LoRAAdapter')
    names = {'normalize_qkv_proj', 'normalize_gate_up_proj'}
    functions = [n for n in klass.body if isinstance(n, ast.FunctionDef) and n.name in names]
    namespace = dict(torch=torch, List=list, Dict=dict)
    exec(compile(ast.Module(body=functions, type_ignores=[]), '<engine normalization>', 'exec'), namespace)
    expected = dict(raw)
    dummy = SimpleNamespace(_is_non_gated_moe_weight=lambda _: False)
    for name in ('normalize_qkv_proj', 'normalize_gate_up_proj'):
        namespace[name](dummy, list(expected), expected)
    assert expected.keys() == actual.keys()
    assert all(torch.equal(expected[k], actual[k]) for k in expected)


def main():
    import torch
    from safetensors.torch import load_file
    p = argparse.ArgumentParser()
    p.add_argument('--arm', choices=['r1', 'r16'], required=True)
    p.add_argument('--count', type=int, required=True)
    p.add_argument('--asset-offset', type=int, default=0)
    p.add_argument('--out', required=True)
    p.add_argument('--release', required=True)
    a = p.parse_args()
    assert os.environ.get('SLURM_JOB_ID'), 'CPU staging requires a Slurm allocation'
    experiment = json.loads(Path('experiment.json').read_text())
    assert experiment['model_family'] == 'gpt_oss'
    manifest = json.loads((Path(experiment['assets']) / f'{a.arm}-manifest.json').read_text())
    manifest = manifest[a.asset_offset:a.asset_offset+a.count]
    assert len(manifest) == a.count
    target = Path(a.out).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        raise ValueError('Refusing to overwrite a live store index')
    # The portable Python build lacks os.memfd_create despite the Linux host
    # supporting it. Call the libc wrapper with the same public Linux flags.
    libc = ctypes.CDLL(None, use_errno=True)
    create = libc.memfd_create
    create.argtypes, create.restype = [ctypes.c_char_p, ctypes.c_uint], ctypes.c_int
    fd = create(b'unique-adapter-cpu', 2)  # MFD_ALLOW_SEALING
    if fd < 0:
        raise OSError(ctypes.get_errno(), 'memfd_create failed')
    layout = None
    adapters = {}
    with os.fdopen(os.dup(fd), 'wb', buffering=8*1024*1024) as stream:
        for i, item in enumerate(manifest):
            raw = load_file(item['path'], device='cpu')
            tensors = normalize(raw)
            if i == 0:
                check_reference(raw, tensors)
            del raw
            offset = stream.tell()
            current_layout = []
            digest = hashlib.sha256()
            for name, tensor in sorted(tensors.items()):
                assert tensor.dtype == torch.bfloat16
                current_layout.append(dict(name=name, shape=list(tensor.shape), numel=tensor.numel(), offset=stream.tell()-offset))
                data = memoryview(tensor.contiguous().view(torch.uint8).numpy()).cast('B')
                stream.write(data)
                digest.update(data)
            if layout is None:
                layout = current_layout
            assert layout == current_layout
            adapters[str(Path(item['path']).parent.resolve())] = dict(
                offset=offset, original_sha256=item['sha256'], normalized_sha256=digest.hexdigest())
            del tensors
            if i % 32 == 0:
                print(json.dumps(dict(staged=i+1, count=a.count, bytes=stream.tell())), flush=True)
    size = os.fstat(fd).st_size
    fcntl.fcntl(fd, getattr(fcntl, 'F_ADD_SEALS', 1033), 1 | 2 | 4 | 8)
    index = dict(ready=True, sealed=True, format='gpt_oss_normalized_bf16_v1',
                 hostname=socket.gethostname(), owner_job=os.environ['SLURM_JOB_ID'],
                 memfd_path=f'/proc/{os.getpid()}/fd/{fd}', bytes=size,
                 layout=layout, adapters=adapters, created=time.time())
    tmp = target.with_suffix('.tmp')
    tmp.write_text(json.dumps(index))
    tmp.replace(target)
    print(json.dumps(dict(ready=True, index=str(target), bytes=size)), flush=True)
    while not Path(a.release).exists():
        time.sleep(2)
    os.close(fd)


if __name__ == '__main__':
    main()
